<?php
/**
 * One-time installer (command line only):
 *   C:\xampp\php\php.exe backend\install.php [--root-pass=SECRET]
 *
 * Creates the `reignfashion` database and a `reign_app` user that can only
 * access that database, writes backend/config.php with a generated password
 * and secret, then applies schema.sql. Re-running keeps the existing config
 * and only re-applies the (idempotent) schema.
 */
declare(strict_types=1);

if (PHP_SAPI !== 'cli') {
    http_response_code(404);
    exit;
}

$opts     = getopt('', ['root-user::', 'root-pass::', 'host::']);
$host     = $opts['host'] ?? '127.0.0.1';
$rootUser = $opts['root-user'] ?? 'root';
$rootPass = $opts['root-pass'] ?? '';
$dbName   = 'reignfashion';
$appUser  = 'reign_app';

$configFile = __DIR__ . '/config.php';
$fresh = !is_file($configFile);

$config = $fresh ? require __DIR__ . '/config.example.php' : require $configFile;
if ($fresh) {
    $config['db']['pass']  = bin2hex(random_bytes(16));
    $config['app_secret']  = bin2hex(random_bytes(32));
}

try {
    $root = new PDO("mysql:host=$host;charset=utf8mb4", $rootUser, $rootPass, [PDO::ATTR_ERRMODE => PDO::ERRMODE_EXCEPTION]);
} catch (PDOException $e) {
    fwrite(STDERR, "Could not connect to MySQL as $rootUser: {$e->getMessage()}\n");
    exit(1);
}

$root->exec("CREATE DATABASE IF NOT EXISTS `$dbName` CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci");

$pass = $config['db']['pass'];
foreach (['localhost', '127.0.0.1'] as $h) {
    $root->exec("CREATE USER IF NOT EXISTS '$appUser'@'$h' IDENTIFIED BY " . $root->quote($pass));
    $root->exec("ALTER USER '$appUser'@'$h' IDENTIFIED BY " . $root->quote($pass));
    $root->exec("GRANT SELECT, INSERT, UPDATE, DELETE, CREATE, ALTER, INDEX, REFERENCES ON `$dbName`.* TO '$appUser'@'$h'");
}
$root->exec('FLUSH PRIVILEGES');

if ($fresh) {
    $export = "<?php\n// Generated by backend/install.php on " . date('Y-m-d H:i') . ". Keep private.\nreturn " . var_export($config, true) . ";\n";
    file_put_contents($configFile, $export);
    echo "Wrote backend/config.php\n";
}

// Apply schema as the app user (proves its permissions work)
$app = new PDO("mysql:host=$host;dbname=$dbName;charset=utf8mb4", $appUser, $pass, [PDO::ATTR_ERRMODE => PDO::ERRMODE_EXCEPTION]);
$sql = file_get_contents(__DIR__ . '/schema.sql');
foreach (array_filter(array_map('trim', preg_split('/;\s*\n/', preg_replace('/^--.*$/m', '', $sql)))) as $stmt) {
    $app->exec($stmt);
}

if (!is_dir(__DIR__ . '/storage/uploads')) {
    mkdir(__DIR__ . '/storage/uploads', 0750, true);
}

$tables = $app->query('SHOW TABLES')->fetchAll(PDO::FETCH_COLUMN);
echo "Database `$dbName` ready. Tables: " . implode(', ', $tables) . "\n";

// Import the gallery tiles currently in index.html (first run only)
require_once __DIR__ . '/gallery.php';
$seeded = seed_gallery_from_html();
echo $seeded ? "Imported $seeded gallery items from index.html\n" : "Gallery already has items; nothing imported\n";
