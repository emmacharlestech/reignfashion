/**
 * Shared layout: writes the same header, mobile menu and footer into every
 * page, marks the current page, and keeps links on clean URLs (no .html).
 *
 *   node tools/build-layout.js
 *
 * To change the menu or footer, edit NAV / footer here (or
 * tools/layout/footer.html) and re-run. Safe to run any number of times.
 */
const fs = require('fs');
const path = require('path');

const ROOT = path.join(__dirname, '..');
const SITE = 'https://reignfashionempire.com/';

/* ---------------------------------------------------------------- menu */
const NAV = [
  { key: 'home', label: 'Home', href: './' },
  {
    key: 'collections', label: 'Collections', href: 'collections',
    children: [
      { key: 'women', label: "Women's Collection", href: 'women' },
      { key: 'men', label: "Men's Collection", href: 'men' },
      { key: 'kids', label: "Kiddies' Collection", href: 'kids' },
      { key: 'collections', label: 'All Collections', href: 'collections' },
    ],
  },
  { key: 'bridal', label: 'Bridal', href: 'bridal' },
  { key: 'aso-ebi', label: 'Aso-Ebi', href: 'aso-ebi' },
  { key: 'academy', label: 'Academy', href: 'academy' },
  { key: 'about', label: 'About', href: 'about' },
  { key: 'contact', label: 'Contact', href: 'contact' },
];

/* Every page and which menu item it belongs to */
const PAGES = {
  'index.html': 'home', 'collections.html': 'collections', 'women.html': 'women', 'men.html': 'men', 'kids.html': 'kids',
  'bridal.html': 'bridal', 'aso-ebi.html': 'aso-ebi', 'academy.html': 'academy', 'about.html': 'about',
  'contact.html': 'contact', 'privacy.html': null,
};
const PARENT_OF = { women: 'collections', men: 'collections', kids: 'collections' };

const chevron = '<svg class="icon icon--chevron" viewBox="0 0 24 24" aria-hidden="true" focusable="false"><path d="m6 9 6 6 6-6"/></svg>';
const cur = (on) => (on ? ' is-active" aria-current="page' : '');

function header(active) {
  const top = PARENT_OF[active] || active;
  const items = NAV.map((item) => {
    if (!item.children) {
      return `          <li><a href="${item.href}" class="nav-link${cur(item.key === active)}">${item.label}</a></li>`;
    }
    const subs = item.children.map((c) =>
      `              <li><a href="${c.href}" class="nav-sub-link${cur(c.key === active && (c.key !== 'collections' || active === 'collections'))}">${c.label}</a></li>`).join('\n');
    return `          <li class="nav-item has-sub">
            <a href="${item.href}" class="nav-link${item.key === top ? ' is-active' : ''}"${item.key === active ? ' aria-current="page"' : ''}>${item.label}</a>
            <button type="button" class="nav-sub-toggle" aria-expanded="false" aria-controls="sub-${item.key}" aria-label="Show ${item.label.toLowerCase()} menu">${chevron}</button>
            <ul class="nav-sub" id="sub-${item.key}">
${subs}
            </ul>
          </li>`;
  }).join('\n');

  const mobile = NAV.map((item) => {
    const link = `<a href="${item.href}" class="mobile-nav-link${cur(item.key === active)}">${item.label}</a>`;
    if (!item.children) return `          <li>${link}</li>`;
    const subs = item.children.filter((c) => c.href !== item.href).map((c) =>
      `              <li><a href="${c.href}" class="mobile-sub-link${cur(c.key === active)}">${c.label}</a></li>`).join('\n');
    return `          <li>${link}
            <ul class="mobile-sub-list">
${subs}
            </ul>
          </li>`;
  }).join('\n');

  return `<!-- LAYOUT:TOP (generated by tools/build-layout.js: edit there, not here) -->
  <a class="skip-link" href="#main">Skip to main content</a>

  <header class="site-header" id="site-header">
    <div class="container header-inner">
      <a href="./" class="wordmark brand">
        <span class="brand__mark" aria-hidden="true"></span>
        <span class="brand__word" aria-hidden="true"></span>
        <span class="visually-hidden">Reign Fashion Empire, home</span>
      </a>

      <nav class="primary-nav" aria-label="Primary">
        <ul class="nav-list">
${items}
        </ul>
      </nav>

      <a href="contact" class="btn btn--dark btn--sm header-cta">Book a Consultation</a>

      <button class="menu-toggle" id="menu-toggle" type="button"
              aria-expanded="false" aria-controls="mobile-menu" aria-label="Open menu">
        <span class="menu-toggle__bar"></span>
        <span class="menu-toggle__bar"></span>
      </button>
    </div>
  </header>

  <div class="mobile-menu" id="mobile-menu" role="dialog" aria-modal="true" aria-label="Site menu" hidden>
    <div class="mobile-menu__inner container">
      <nav aria-label="Mobile">
        <ul class="mobile-nav-list">
${mobile}
        </ul>
      </nav>
      <div class="mobile-menu__footer">
        <a href="contact" class="btn btn--gold mobile-nav-link">Book a Consultation</a>
        <p class="mobile-menu__note">Bridal · Aso-Ebi · Ready-to-Wear · Academy</p>
      </div>
    </div>
  </div>
  <!-- /LAYOUT:TOP -->`;
}

/* -------------------------------------------------------------- footer */
const FOOTER_FILE = path.join(__dirname, 'layout', 'footer.html');

/* ------------------------------------------------------- link cleaning */
const PAGE_NAMES = Object.keys(PAGES).map((f) => f.replace('.html', ''));
function cleanLinks(html) {
  return html
    .replace(/href="index\.html(#[^"]*)?"/g, (m, hash) => `href="./${hash || ''}"`)
    .replace(new RegExp(`href="(${PAGE_NAMES.join('|')})\\.html([?#][^"]*)?"`, 'g'), (m, name, rest) => `href="${name}${rest || ''}"`)
    .replace(new RegExp(`(https://reignfashionempire\\.com/)(${PAGE_NAMES.join('|')})\\.html`, 'g'), '$1$2')
    .replace(/https:\/\/reignfashionempire\.com\/index(?=")/g, 'https://reignfashionempire.com/');
}

/* --------------------------------------------------------------- build */
const TOP_FIRST = /  <a class="skip-link"[\s\S]*?(?=  <main id="main">)/;
const TOP_MARKED = /<!-- LAYOUT:TOP[\s\S]*?<!-- \/LAYOUT:TOP -->/;
const FOOT_FIRST = /  <!-- =+\n\s+FOOTER[\s\S]*?<\/footer>/;
const FOOT_MARKED = /<!-- LAYOUT:FOOTER[\s\S]*?<!-- \/LAYOUT:FOOTER -->/;

let footerTpl = fs.existsSync(FOOTER_FILE) ? fs.readFileSync(FOOTER_FILE, 'utf8') : null;

for (const [file, active] of Object.entries(PAGES)) {
  const full = path.join(ROOT, file);
  if (!fs.existsSync(full)) { console.log(`skip ${file} (not created yet)`); continue; }
  let html = fs.readFileSync(full, 'utf8');

  // Header + mobile menu
  if (TOP_MARKED.test(html)) html = html.replace(TOP_MARKED, header(active));
  else if (TOP_FIRST.test(html)) html = html.replace(TOP_FIRST, '  ' + header(active) + '\n\n');
  else throw new Error(`No header region found in ${file}`);

  // Footer: the first page that has one provides the template
  if (!footerTpl) {
    const m = html.match(FOOT_MARKED) || html.match(FOOT_FIRST);
    if (!m) throw new Error(`No footer found in ${file}`);
    footerTpl = m[0].replace(/^<!-- LAYOUT:FOOTER[^>]*-->\n?/, '').replace(/\n?\s*<!-- \/LAYOUT:FOOTER -->$/, '').replace(/^  /, '');
    footerTpl = cleanLinks(footerTpl).replace(/href="\.\/" class="footer__top-link"/, 'href="#main" class="footer__top-link"');
    fs.mkdirSync(path.dirname(FOOTER_FILE), { recursive: true });
    fs.writeFileSync(FOOTER_FILE, footerTpl);
  }
  const footerBlock = `<!-- LAYOUT:FOOTER (generated by tools/build-layout.js from tools/layout/footer.html) -->\n  ${footerTpl.trim()}\n  <!-- /LAYOUT:FOOTER -->`;
  if (FOOT_MARKED.test(html)) html = html.replace(FOOT_MARKED, footerBlock);
  else if (FOOT_FIRST.test(html)) html = html.replace(FOOT_FIRST, '  ' + footerBlock);
  else throw new Error(`No footer region found in ${file}`);

  fs.writeFileSync(full, cleanLinks(html));
  console.log(`${file.padEnd(17)} active: ${active || '-'}`);
}
